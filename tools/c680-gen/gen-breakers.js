// Generates MSFSBlindAssist/Aircraft/Citation680/C680BreakerTable.cs from the Skyward
// Citation Sovereign+ package's SOV_Circuit_Breakers.xml: one row per SKYWARD_GT_Circuit_Breaker
// (its L:var, the electrical line its click toggles, and a spoken label).
// Run: node tools/c680-gen/gen-breakers.js   (set C680_PKG to the package folder if it moved)
const fs = require('fs'), path = require('path');
const pkg = process.env.C680_PKG || path.join(process.env.LOCALAPPDATA,
  'Packages/Microsoft.Limitless_8wekyb3d8bbwe/LocalCache/Packages/Community/skyward-cessna-citation-c680');
const xml = fs.readFileSync(path.join(pkg, 'SimObjects/Airplanes/cessna-citation-c680/model/SOV_Circuit_Breakers.xml'), 'utf8');

const ACRONYMS = { pfd: 'PFD', mfd: 'MFD', gtc: 'GTC', tr: 'T/R', apu: 'APU', cvr: 'CVR', xpdr: 'XPDR', adc: 'ADC', ahrs: 'AHRS',
  gps: 'GPS', fms: 'FMS', com: 'COM', nav: 'NAV', adf: 'ADF', dme: 'DME', tcas: 'TCAS', taws: 'TAWS', elt: 'ELT', ecs: 'ECS',
  fadec: 'FADEC', gcu: 'GCU', tru: 'TRU', dc: 'DC', ac: 'AC', ldg: 'LDG', cas: 'CAS', ap: 'AP', at: 'AT', yd: 'YD', stby: 'STBY',
  emer: 'EMER', cont: 'CONT', ign: 'IGN', hyd: 'HYD', eng: 'ENG', aux: 'AUX', ind: 'IND', lts: 'LTS', lt: 'LT', pwr: 'PWR', aoa: 'AOA', avn: 'AVN', afcs: 'AFCS', sov: 'SOV', fw: 'FW', iau: 'IAU', ws: 'WS', batt: 'BATT', gcu: 'GCU', fms: 'FMS',
  sw: 'SW', vhf: 'VHF', hf: 'HF', ils: 'ILS', vor: 'VOR', rad: 'RAD', alt: 'ALT', wx: 'WX', rmt: 'RMT' };

function label(node) {
  let words = node.replace(/^CB_/, '').split('_').filter(Boolean);
  const side = words[0] === 'L' ? 'Left' : words[0] === 'R' ? 'Right' : null;
  if (side) words = words.slice(1);
  const pretty = words.map(w => {
    const lw = w.toLowerCase();
    if (ACRONYMS[lw]) return ACRONYMS[lw];
    if (/^\d+$/.test(w)) return w;
    return lw.charAt(0).toUpperCase() + lw.slice(1);
  });
  return (side ? side + ' ' : '') + pretty.join(' ') + ' Breaker';
}

const rows = [];
for (const m of xml.matchAll(/<UseTemplate Name="SKYWARD_GT_Circuit_Breaker">([\s\S]*?)<\/UseTemplate>/g)) {
  const body = m[1];
  const node = (body.match(/<NODE_ID>([^<]+)<\/NODE_ID>/) || [])[1];
  const line = (body.match(/&apos;([A-Za-z0-9_]+)&apos;_n \(&gt;K:ELECTRICAL_LINE_BREAKER_TOGGLE\)/) || [])[1];
  if (!node || !line) { console.error('skipped a breaker without a node or line:', (node || body.slice(0, 80))); continue; }
  rows.push({ key: 'C680_' + node, lvar: node, line, label: label(node) });
}
// Labels must be unique (two panel rows may never share a spoken name): disambiguate with the line.
const seen = new Map();
for (const r of rows) seen.set(r.label, (seen.get(r.label) || 0) + 1);
for (const r of rows) if (seen.get(r.label) > 1) r.label = r.label.replace(/ Breaker$/, '') + ' (' + r.line + ') Breaker';

const cs = ['// <auto-generated> by tools/c680-gen/gen-breakers.js — do not edit by hand; rerun the generator.',
  'namespace MSFSBlindAssist.Aircraft.Citation680;', '',
  '/// <summary>Every circuit breaker the Sovereign+ model declares: its L:var, the electrical line its click toggles, and its spoken label.</summary>',
  'public static class C680BreakerTable', '{',
  '    public static readonly IReadOnlyList<(string Key, string LVar, string Line, string Label)> Rows = new List<(string, string, string, string)>', '    {'];
for (const r of rows) cs.push(`        ("${r.key}", "${r.lvar}", "${r.line}", "${r.label}"),`);
cs.push('    };', '}');
fs.writeFileSync(path.join(__dirname, '../../MSFSBlindAssist/Aircraft/Citation680/C680BreakerTable.cs'), cs.join('\n') + '\n');
console.log('breakers', rows.length);
